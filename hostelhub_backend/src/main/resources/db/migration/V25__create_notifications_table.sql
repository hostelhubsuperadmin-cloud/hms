-- Creates the notifications table for HostelHub.

CREATE TABLE notifications (
                               id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                               recipient_user_id BIGINT NOT NULL,
                               hostel_id BIGINT,

                               notification_type VARCHAR(50) NOT NULL,
                               title VARCHAR(200) NOT NULL,
                               message VARCHAR(2000) NOT NULL,
                               target_url VARCHAR(500),

                               is_read BOOLEAN NOT NULL DEFAULT FALSE,
                               delivery_status VARCHAR(20) NOT NULL DEFAULT 'PENDING',

                               created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                               read_at TIMESTAMPTZ,

                               CONSTRAINT fk_notifications_recipient
                                   FOREIGN KEY (recipient_user_id)
                                       REFERENCES users(id)
                                       ON DELETE RESTRICT,

                               CONSTRAINT fk_notifications_hostel
                                   FOREIGN KEY (hostel_id)
                                       REFERENCES hostels(id)
                                       ON DELETE RESTRICT,

                               CONSTRAINT chk_notifications_delivery_status
                                   CHECK (delivery_status IN ('PENDING', 'SENT', 'FAILED'))
);

CREATE INDEX idx_notification_recipient
    ON notifications(recipient_user_id, created_at);

CREATE INDEX idx_notification_unread
    ON notifications(recipient_user_id, is_read);
