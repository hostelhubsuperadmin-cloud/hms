
CREATE TABLE invoices (
                          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                          hostel_id BIGINT NOT NULL,
                          hostler_id BIGINT NOT NULL,
                          allocation_id BIGINT NOT NULL,

                          period_start DATE NOT NULL,
                          period_end DATE NOT NULL,
                          issued_at TIMESTAMPTZ,
                          due_date DATE NOT NULL,

                          subtotal NUMERIC(12, 2) NOT NULL,
                          amount_paid NUMERIC(12, 2) NOT NULL DEFAULT 0.00,
                          currency VARCHAR(3) NOT NULL DEFAULT 'INR',
                          status VARCHAR(25) NOT NULL DEFAULT 'DRAFT',

                          created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                          CONSTRAINT fk_invoices_hostel
                              FOREIGN KEY (hostel_id)
                                  REFERENCES hostels(id)
                                  ON DELETE RESTRICT,

                          CONSTRAINT fk_invoices_hostler
                              FOREIGN KEY (hostler_id)
                                  REFERENCES users(id)
                                  ON DELETE RESTRICT,

                          CONSTRAINT fk_invoices_allocation
                              FOREIGN KEY (allocation_id)
                                  REFERENCES allocations(id)
                                  ON DELETE RESTRICT,

                          CONSTRAINT chk_invoices_period
                              CHECK (period_end >= period_start),

                          CONSTRAINT chk_invoices_amounts
                              CHECK (subtotal >= 0 AND amount_paid >= 0),

                          CONSTRAINT chk_invoices_status
                              CHECK (
                                  status IN (
                                             'DRAFT',
                                             'ISSUED',
                                             'PARTIALLY_PAID',
                                             'PAID',
                                             'OVERDUE',
                                             'VOID'
                                      )
                                  ),

                          CONSTRAINT chk_invoices_currency
                              CHECK (currency ~ '^[A-Z]{3}$')
    );

CREATE INDEX idx_invoice_hostler
    ON invoices(hostler_id);

CREATE INDEX idx_invoice_hostel_status
    ON invoices(hostel_id, status);
