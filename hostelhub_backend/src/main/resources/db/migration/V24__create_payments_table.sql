-- V24__create_payments_table.sql
-- Creates the payments table for HostelHub billing.
-- Requires the invoices table from V23.

CREATE TABLE payments (
                          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                          invoice_id BIGINT NOT NULL,
                          hostel_id BIGINT NOT NULL,
                          hostler_id BIGINT NOT NULL,

                          amount NUMERIC(12, 2) NOT NULL,
                          currency VARCHAR(3) NOT NULL DEFAULT 'INR',

                          method VARCHAR(20) NOT NULL,
                          status VARCHAR(20) NOT NULL DEFAULT 'PENDING',

                          provider_reference VARCHAR(150),
                          idempotency_key VARCHAR(100),

                          submitted_by BIGINT,
                          reviewed_by BIGINT,
                          review_note VARCHAR(500),

                          created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                          verified_at TIMESTAMPTZ,

                          CONSTRAINT uq_payments_provider_reference
                              UNIQUE (provider_reference),

                          CONSTRAINT uq_payments_idempotency_key
                              UNIQUE (idempotency_key),

                          CONSTRAINT fk_payments_invoice
                              FOREIGN KEY (invoice_id)
                                  REFERENCES invoices(id)
                                  ON DELETE RESTRICT,

                          CONSTRAINT fk_payments_hostel
                              FOREIGN KEY (hostel_id)
                                  REFERENCES hostels(id)
                                  ON DELETE RESTRICT,

                          CONSTRAINT fk_payments_hostler
                              FOREIGN KEY (hostler_id)
                                  REFERENCES users(id)
                                  ON DELETE RESTRICT,

                          CONSTRAINT fk_payments_submitted_by
                              FOREIGN KEY (submitted_by)
                                  REFERENCES users(id)
                                  ON DELETE RESTRICT,

                          CONSTRAINT fk_payments_reviewed_by
                              FOREIGN KEY (reviewed_by)
                                  REFERENCES users(id)
                                  ON DELETE RESTRICT,

                          CONSTRAINT chk_payments_amount
                              CHECK (amount > 0),

                          CONSTRAINT chk_payments_currency
                              CHECK (currency ~ '^[A-Z]{3}$'),

    CONSTRAINT chk_payments_method
        CHECK (method IN ('MANUAL', 'ONLINE')),

    CONSTRAINT chk_payments_status
        CHECK (
            status IN (
                'PENDING',
                'SUBMITTED',
                'PROCESSING',
                'SUCCESS',
                'FAILED',
                'REJECTED',
                'REFUNDED'
            )
        )
);

CREATE INDEX idx_payment_invoice
    ON payments(invoice_id);

CREATE INDEX idx_payment_hostler
    ON payments(hostler_id);

CREATE INDEX idx_payment_provider_ref
    ON payments(provider_reference);