-- HostelHub V22: Create audit events table.
-- Keep all previously applied migrations unchanged.

CREATE TABLE public.audit_events (
                                     id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                     actor_user_id BIGINT,
                                     hostel_id BIGINT,

                                     action VARCHAR(100) NOT NULL,
                                     entity_type VARCHAR(100) NOT NULL,
                                     entity_id VARCHAR(100),

                                     outcome VARCHAR(30) NOT NULL,
                                     details VARCHAR(2000),
                                     correlation_id VARCHAR(100),

                                     created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                     CONSTRAINT fk_audit_events_actor
                                         FOREIGN KEY (actor_user_id)
                                             REFERENCES public.users(id)
                                             ON DELETE RESTRICT,

                                     CONSTRAINT fk_audit_events_hostel
                                         FOREIGN KEY (hostel_id)
                                             REFERENCES public.hostels(id)
                                             ON DELETE RESTRICT
);

CREATE INDEX idx_audit_actor
    ON public.audit_events(actor_user_id);

CREATE INDEX idx_audit_created
    ON public.audit_events(created_at);

CREATE INDEX idx_audit_entity
    ON public.audit_events(entity_type, entity_id);